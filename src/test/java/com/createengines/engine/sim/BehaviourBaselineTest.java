package com.createengines.engine.sim;

import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

/**
 * Factories built on one version must work the same on every later version of the same major release. This pins what
 * an engine does: the torque curve of a spread of builds (every fuel, crude and precision parts, one and six
 * cylinders, every kind of boost) and the shipped settings in {@link Tuning}, against
 * {@code src/test/resources/compat/behaviour.txt}, recorded as shipped in 1.3.
 * <p>
 * A failure means a change to how existing builds run. Do not edit the numbers to make it pass: in 1.x, give the
 * change its own switch (a new block, item or config option that existing builds do not use) and leave the old
 * behaviour as the default. Only a major release (2.0) may move these numbers, and then the file is regenerated by
 * hand. New builds are appended with {@code COMPAT_REGEN=1}; existing lines are never rewritten by it.
 */
class BehaviourBaselineTest {

	private static final Path FILE = Path.of("").toAbsolutePath().resolve("src/test/resources/compat/behaviour.txt");
	private static final double TOLERANCE = 1e-6;

	@BeforeEach
	void shippedSettings() {
		Tuning.reset();
	}

	@Test
	void existingBuildsRunAsTheyDid() throws IOException {
		Map<String, String> shipped = read();
		Map<String, String> now = measure();

		List<String> missing = new ArrayList<>();
		List<String> drifted = new ArrayList<>();
		for (Map.Entry<String, String> e : shipped.entrySet()) {
			String value = now.get(e.getKey());
			if (value == null)
				missing.add(e.getKey());
			else if (!same(e.getValue(), value))
				drifted.add(e.getKey() + "\n    shipped " + e.getValue() + "\n    now     " + value);
		}

		List<String> added = new ArrayList<>();
		for (String key : now.keySet())
			if (!shipped.containsKey(key))
				added.add(key);
		if (System.getenv("COMPAT_REGEN") != null && !added.isEmpty()) {
			Map<String, String> merged = new TreeMap<>(shipped);
			for (String key : added)
				merged.put(key, now.get(key));
			write(merged);
			System.out.println("behaviour baseline: appended " + added.size() + " builds");
		}

		String advice = "\nBuilt factories rely on this. Keep the old behaviour as the default and put the change behind "
			+ "a new block, item or config switch. Only a major release (2.0) may change these numbers.";
		assertTrue(missing.isEmpty(), "Baseline builds no longer measurable: " + missing + advice);
		assertTrue(drifted.isEmpty(), "Existing builds now run differently:\n" + String.join("\n", drifted) + advice);
	}

	private static Map<String, String> measure() {
		Map<String, String> out = new TreeMap<>();

		for (Field field : Tuning.class.getFields()) {
			if (!Modifier.isStatic(field.getModifiers()))
				continue;
			try {
				out.put("tuning:" + field.getName(), String.valueOf(field.get(null)));
			} catch (IllegalAccessException e) {
				throw new IllegalStateException(e);
			}
		}

		Map<String, FuelSpec> fuels = new TreeMap<>();
		for (Field field : FuelSpec.class.getFields()) {
			if (Modifier.isStatic(field.getModifiers()) && field.getType() == FuelSpec.class) {
				try {
					fuels.put(field.getName(), (FuelSpec) field.get(null));
				} catch (IllegalAccessException e) {
					throw new IllegalStateException(e);
				}
			}
		}
		Map<String, CylinderSpec> specs = new TreeMap<>();
		specs.put("crude", CylinderSpec.CRUDE);
		specs.put("precise", CylinderSpec.build(true, true, true, true));
		specs.put("injector", CylinderSpec.build(false, false, false, true));

		for (Map.Entry<String, FuelSpec> fuel : fuels.entrySet())
			for (Map.Entry<String, CylinderSpec> spec : specs.entrySet())
				for (int cylinders : new int[] {1, 6})
					for (String boost : new String[] {"none", "turbo", "turbo3", "blower", "turbo+intercooler"})
						for (boolean spark : new boolean[] {false, true}) {
							String label = "run:" + fuel.getKey() + ":" + spec.getKey() + ":" + cylinders + "cyl:" + boost
								+ (spark ? ":spark" : ":compression");
							out.put(label, curve(fuel.getValue(), spec.getValue(), cylinders, boost, spark));
						}
		return out;
	}

	/** The torque curve at Create's usual speeds, as the dynamometer measures it, rounded for the file. */
	private static String curve(FuelSpec fuel, CylinderSpec spec, int cylinders, String boost, boolean spark) {
		Camshaft cam = new Camshaft();
		List<CylinderModel> models = new ArrayList<>();
		double step = 720d / cylinders;
		for (int i = 0; i < cylinders; i++) {
			double fire = i * step;
			CylinderModel model = new CylinderModel(spec, CamProfile.BASIC, fire % 360, cam, fire / 2);
			model.fuelSupply = MixtureTest.unlimited(fuel);
			model.metering = 2;
			model.airMatch = 1;
			model.ignition = spark ? IgnitionSource.UNLIMITED : IgnitionSource.NONE;
			models.add(model);
		}
		EngineSimulation sim = new EngineSimulation(models, cylinders * 0.35 + 1, (cylinders * 2 + 1) * 0.01);
		for (CylinderModel model : models)
			model.resetGas(0);
		int turbos = boost.startsWith("turbo3") ? 3 : boost.startsWith("turbo") ? 1 : 0;
		for (int t = 0; t < turbos; t++) {
			Turbocharger unit = new Turbocharger(models, models, 1);
			unit.limit = Turbocharger.DEFAULT_LIMIT;
			sim.addTurbo(unit);
		}
		if (boost.equals("blower")) {
			Supercharger unit = new Supercharger(models);
			unit.rpm = Supercharger.DESIGN_RPM;
			sim.addSupercharger(unit);
		}
		if (boost.endsWith("intercooler"))
			sim.addIntercooler(new Intercooler(models));

		double[] torque = Dynamometer.torqueCurve(sim);
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < torque.length; i++) {
			if (i > 0)
				sb.append(',');
			sb.append(String.format(java.util.Locale.ROOT, "%.5f", torque[i]));
		}
		return sb.toString();
	}

	private static boolean same(String shipped, String now) {
		String[] a = shipped.split(",");
		String[] b = now.split(",");
		if (a.length != b.length)
			return false;
		for (int i = 0; i < a.length; i++) {
			if (a[i].equals(b[i]))
				continue;
			try {
				double x = Double.parseDouble(a[i]);
				double y = Double.parseDouble(b[i]);
				if (Math.abs(x - y) > TOLERANCE * Math.max(1, Math.abs(x)))
					return false;
			} catch (NumberFormatException e) {
				return false;
			}
		}
		return true;
	}

	private static Map<String, String> read() throws IOException {
		Map<String, String> out = new TreeMap<>();
		if (!Files.exists(FILE))
			return out;
		for (String line : Files.readAllLines(FILE, StandardCharsets.UTF_8)) {
			if (line.isBlank() || line.startsWith("#"))
				continue;
			int tab = line.indexOf('\t');
			out.put(line.substring(0, tab), line.substring(tab + 1));
		}
		return out;
	}

	private static void write(Map<String, String> entries) throws IOException {
		List<String> lines = new ArrayList<>();
		lines.add("# Engine behaviour as shipped. See BehaviourBaselineTest. Append only; changing a number is a 2.0 change.");
		for (Map.Entry<String, String> e : entries.entrySet())
			lines.add(e.getKey() + "\t" + e.getValue());
		Files.createDirectories(FILE.getParent());
		Files.write(FILE, lines, StandardCharsets.UTF_8);
	}
}
