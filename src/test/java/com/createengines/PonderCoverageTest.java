package com.createengines;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import org.junit.jupiter.api.Test;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;

/**
 * The Ponder pages say what the parts do in 2.0. Each page's text is the shipped lang file's {@code create_engines.ponder.<page>.*}
 * entries (regenerated by {@code runData} from the scenes' own text), so this reads what a player reads. It pins the facts a
 * page has to carry, and the one claim that was once wrong, so a later change cannot quietly take them out or bring it back.
 */
class PonderCoverageTest {

	private static final Path LANG = Path.of("src/generated/resources/assets/create_engines/lang/en_us.json");

	private static Map<String, String> lang() throws IOException {
		return new Gson().fromJson(Files.readString(LANG, StandardCharsets.UTF_8), new TypeToken<TreeMap<String, String>>() {
		}.getType());
	}

	/** Everything a page says, in one string, for a search. */
	private static String page(Map<String, String> lang, String page) {
		String prefix = "create_engines.ponder." + page + ".";
		StringBuilder out = new StringBuilder();
		lang.forEach((key, value) -> {
			if (key.startsWith(prefix))
				out.append(value)
					.append('\n');
		});
		assertTrue(out.length() > 0, "no Ponder text for the page " + page + " in " + LANG);
		return out.toString();
	}

	private static void says(Map<String, String> lang, String page, List<String> missing, String... facts) {
		String text = page(lang, page);
		for (String fact : facts)
			if (!text.contains(fact))
				missing.add(page + ": " + fact);
	}

	@Test
	void everyPartPageSaysWhatIsNewInTwoPointZero() throws IOException {
		Map<String, String> lang = lang();
		List<String> missing = new ArrayList<>();
		// Battery depth: banks, the lamps, the comparator, cold, and the starter's draw
		says(lang, "spark", missing, "one bank", "lamps", "Comparator", "Cold costs charge", "draws on the batteries");
		// Alternator readout and several on one engine
		says(lang, "spark", missing, "what share of the engine's rating", "fit several");
		// The starter: a hand crank on its own shaft engages it with no signal
		says(lang, "starter", missing, "Starter's own shaft", "no redstone signal");
		// Compressor readout, and the blow-off jet
		says(lang, "turbocharger", missing, "share of that limit", "thinning jet");
		says(lang, "supercharger", missing, "share of its boost limit");
		// Port count: diminishing returns
		says(lang, "airflow", missing, "One opening for each head", "two thirds");
		// Auto shift profiles, Black Box replay, Display Link sources
		says(lang, "transmission", missing, "Economy");
		says(lang, "black_box", missing, "Replay dial");
		says(lang, "engine_readouts", missing, "Engine Fault", "Transmission Gear", "Battery Charge");
		assertTrue(missing.isEmpty(), "Ponder pages that no longer say what is new: " + missing);
	}

	/**
	 * The slow-crank half of cranking draw was built and dropped (a starter slowed by a flat battery stopped engines that start from
	 * the flat battery they are placed with), so a page must not promise it.
	 */
	@Test
	void noPageSaysAWeakBatterySlowsTheStarter() throws IOException {
		for (Map.Entry<String, String> entry : lang().entrySet())
			if (entry.getKey()
				.startsWith("create_engines.ponder."))
				assertFalse(entry.getValue()
					.contains("turns it more slowly"), entry.getKey() + " says a starter slows down as the batteries run low, which it does not");
	}

	/** 1.x counted one opening for two heads as full breathing; 2.0's curve does not, and the airflow page must not say it does. */
	@Test
	void theAirflowPageDoesNotSayAnOpeningComfortablyServesTwoCylinders() throws IOException {
		assertFalse(page(lang(), "airflow").contains("comfortably serves two"),
			"one opening for two heads is about two thirds of full breathing in 2.0");
	}
}
